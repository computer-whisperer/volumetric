/// Glyph cell: five columns and a one-column gap.
const ADVANCE: u32 = 6;

/// The pixel size of `text` drawn at `scale`, gap after the last glyph
/// excluded.
pub fn text_size(text: &str, scale: u32) -> (u32, u32) {
    let n = text.chars().count() as u32;
    if n == 0 {
        return (0, 7 * scale);
    }
    ((n * ADVANCE - 1) * scale, 7 * scale)
}

/// Draws `text` with its top-left corner at `(x, y)`, each font pixel a
/// `scale` x `scale` block, calling `plot` for every lit pixel. Pixels
/// left of or above the origin are skipped.
pub fn draw_text(text: &str, x: i64, y: i64, scale: u32, mut plot: impl FnMut(u32, u32)) {
    let scale = scale.max(1);
    for (i, c) in text.chars().enumerate() {
        let rows = glyph(c);
        for (row, bits) in rows.iter().enumerate() {
            for col in 0..5u32 {
                if bits & (0x10 >> col) == 0 {
                    continue;
                }
                let gx = x + i64::from((i as u32 * ADVANCE + col) * scale);
                let gy = y + i64::from(row as u32 * scale);
                for dy in 0..scale {
                    for dx in 0..scale {
                        let (px, py) = (gx + i64::from(dx), gy + i64::from(dy));
                        if px >= 0 && py >= 0 {
                            plot(px as u32, py as u32);
                        }
                    }
                }
            }
        }
    }
}

/// A label: `text` on a dark box with a one-pixel-block margin, its
/// top-left at `(x, y)`, through `plot(px, py, lit)`. Returns the box size.
pub fn draw_label(
    text: &str,
    x: i64,
    y: i64,
    scale: u32,
    mut plot: impl FnMut(u32, u32, bool),
) -> (u32, u32) {
    let scale = scale.max(1);
    let (tw, th) = text_size(text, scale);
    let (bw, bh) = (tw + 2 * scale, th + 2 * scale);
    for dy in 0..bh {
        for dx in 0..bw {
            let (px, py) = (x + i64::from(dx), y + i64::from(dy));
            if px >= 0 && py >= 0 {
                plot(px as u32, py as u32, false);
            }
        }
    }
    draw_text(
        text,
        x + i64::from(scale),
        y + i64::from(scale),
        scale,
        |px, py| plot(px, py, true),
    );
    (bw, bh)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_five_by_seven_and_text_measures_by_advance() {
        for c in "AZaz09_-.:()/ ".chars() {
            assert!(glyph(c).iter().all(|row| *row < 0x20), "{c}");
        }
        assert_eq!(text_size("", 1), (0, 7));
        assert_eq!(text_size("ab", 1), (11, 7));
        assert_eq!(text_size("ab", 3), (33, 21));
        // Every letter and digit has ink; a space has none; an unknown
        // character is a box.
        for c in ('A'..='Z').chain('a'..='z').chain('0'..='9') {
            assert!(glyph(c).iter().any(|row| *row != 0), "{c} is blank");
        }
        assert_eq!(glyph(' '), [0; 7]);
        assert_eq!(glyph('~'), glyph('#'));
    }

    #[test]
    fn text_draws_at_scale_and_clips_to_the_origin() {
        let mut lit = Vec::new();
        draw_text("I", 2, 3, 1, |x, y| lit.push((x, y)));
        // The I's top bar spans columns 1..=3, so pixels x = 3..=5 at y = 3.
        assert!(lit.contains(&(3, 3)) && lit.contains(&(5, 3)) && !lit.contains(&(2, 3)));
        assert!(lit.contains(&(4, 9)), "the stem reaches the bottom row");
        let mut count = 0;
        draw_text("I", 0, 0, 2, |_, _| count += 1);
        let ones: u32 = glyph('I').iter().map(|r| r.count_ones()).sum();
        assert_eq!(count, ones * 4);
        // Off the top-left corner nothing is plotted.
        let mut count = 0;
        draw_text("I", -20, -20, 1, |_, _| count += 1);
        assert_eq!(count, 0);
        // A label boxes its text with a block's margin.
        let mut box_px = 0;
        let mut ink = 0;
        let size = draw_label(
            "ab",
            0,
            0,
            2,
            |_, _, lit| if lit { ink += 1 } else { box_px += 1 },
        );
        assert_eq!(size, (11 * 2 + 4, 14 + 4));
        assert_eq!(box_px, (11 * 2 + 4) * (14 + 4));
        assert!(ink > 0);
    }
}
