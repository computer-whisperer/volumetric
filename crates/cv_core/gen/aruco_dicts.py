#!/usr/bin/env python3
"""Regenerates src/dict_tables.rs from OpenCV's predefined marker dictionaries.

Run with a Python that has cv2 (the scanner's venv does):
    python gen/aruco_dicts.py > src/dict_tables.rs
"""
import cv2

TABLES = [("DICT_5X5_100", "ARUCO_5X5_100_CODES", cv2.aruco.DICT_5X5_100, 5),
          ("DICT_4X4_50", "ARUCO_4X4_50_CODES", cv2.aruco.DICT_4X4_50, 4),
          ("DICT_APRILTAG_36h11", "APRILTAG_36H11_CODES", cv2.aruco.DICT_APRILTAG_36h11, 6)]

print("//! Marker dictionaries as data: each marker's bits in the rotation OpenCV")
print("//! calls 0, row-major from the top-left cell, most significant bit first.")
print("//! Generated by `gen/aruco_dicts.py` from OpenCV 5.0; do not edit.")
print()
for name, const, dic, n in TABLES:
    d = cv2.aruco.getPredefinedDictionary(dic)
    bl = d.bytesList
    print(f"/// OpenCV `{name}`: {bl.shape[0]} markers of {n}x{n} bits, {d.maxCorrectionBits} correction bits.")
    print(f"pub const {const}: [u64; {bl.shape[0]}] = [")
    for i in range(bl.shape[0]):
        bits = cv2.aruco.Dictionary.getBitsFromByteList(bl[i:i + 1], n)
        print("    0b" + "".join(str(int(b)) for b in bits.flatten()) + ",")
    print("];")
    print()
